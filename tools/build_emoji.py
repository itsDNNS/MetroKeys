#!/usr/bin/env python3
"""Builds the emoji page data of MetroKeys (spec/01-layouts.md §7.3, spec/data/emoji.json).

Usage (from the repository root):
    python3 tools/build_emoji.py download   # fetch emoji-test.txt into build-data/emoji and verify its hash
    python3 tools/build_emoji.py build      # write app/src/main/assets/emoji/emoji.txt

Each category of spec/data/emoji.json is filled from the Unicode file emoji-test.txt: the listed group/subgroup
entries in the order of emoji.json, within each entry the emoji in the order of emoji-test.txt, fully-qualified
emoji only, skin-tone variants left out. The "emoticons" category is the fixed list of text smileys given in
emoji.json (`source.items`, 01 §7.3); the "recent" category is built at run time.

Output format (UTF-8): comment lines start with '#'; every other line is "<category id>\t<item> <item> …".
Items never contain spaces. The output is deterministic.
"""

import hashlib
import json
import os
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC_DIR = os.path.join(ROOT, "build-data", "emoji")
SRC = os.path.join(SRC_DIR, "emoji-test.txt")
OUT = os.path.join(ROOT, "app", "src", "main", "assets", "emoji", "emoji.txt")
SPEC = os.path.join(ROOT, "spec", "data", "emoji.json")

URL = "https://www.unicode.org/Public/18.0.0/emoji/emoji-test.txt"
VERSION = "18.0"
SHA256 = "8f3735cda1f92a779d78af67cf86066bb1f07143dc22f2ac29394d9bc57ab21a"

SKIN_TONES = set(range(0x1F3FB, 0x1F400))

def download():
    os.makedirs(SRC_DIR, exist_ok=True)
    if not os.path.exists(SRC):
        print("downloading", URL)
        urllib.request.urlretrieve(URL, SRC)
    verify()


def verify():
    with open(SRC, "rb") as f:
        digest = hashlib.sha256(f.read()).hexdigest()
    if digest != SHA256:
        sys.exit(f"{SRC}: sha256 {digest} does not match {SHA256}")


def parse():
    """Returns a list of (group, subgroup, emoji) for the fully-qualified entries in file order."""
    out = []
    group = subgroup = None
    with open(SRC, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("# group:"):
                group = line[len("# group:"):].strip()
            elif line.startswith("# subgroup:"):
                subgroup = line[len("# subgroup:"):].strip()
            elif line and not line.startswith("#"):
                fields, _, _ = line.partition("#")
                cps, _, status = fields.partition(";")
                if status.strip() != "fully-qualified":
                    continue
                points = [int(p, 16) for p in cps.split()]
                if any(p in SKIN_TONES for p in points):
                    continue
                out.append((group, subgroup, "".join(chr(p) for p in points)))
    return out


def build():
    verify()
    entries = parse()
    with open(SPEC, encoding="utf-8") as f:
        spec = json.load(f)
    lines = [
        "# MetroKeys emoji page data, generated by tools/build_emoji.py - do not edit.",
        f"# Source: Unicode emoji-test.txt, Emoji {VERSION} ({URL}), sha256 {SHA256}.",
        "# Unicode data: Copyright (c) Unicode, Inc., Unicode License v3 (see licenses/Unicode-LICENSE.txt).",
        "# Emoticons: the list of spec/data/emoji.json.",
    ]
    for cat in spec["categories"]:
        cid = cat["id"]
        if cat.get("dynamic"):
            continue
        source = cat["source"]
        if source["kind"] == "text-emoticons":
            items = source["items"]
        else:
            items = []
            seen = set()
            for sel in source["groups"]:
                for g, sg, e in entries:
                    if g == sel["group"] and (sel["subgroup"] == "*" or sg == sel["subgroup"]) and e not in seen:
                        seen.add(e)
                        items.append(e)
        assert all(" " not in i for i in items)
        lines.append(f"{cid}\t{' '.join(items)}")
        print(f"{cid}: {len(items)} items")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    if len(sys.argv) != 2 or sys.argv[1] not in ("download", "build"):
        sys.exit(__doc__)
    download() if sys.argv[1] == "download" else build()
